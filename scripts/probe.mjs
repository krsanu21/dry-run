import { chromium } from "@playwright/test";
import fs from "node:fs";
const [lang, mode, codeFile, argsJson = "[]"] = process.argv.slice(2);
if (!codeFile) throw new Error("usage: probe.mjs <py|js> <function|script> <code-file> [args-json]");
const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
page.on("pageerror", (e) => errs.push("pageerror: " + e.message + (process.env.STACK ? "\n" + String(e.stack).split("\n").slice(0, 8).join("\n") : "")));
page.on("console", (m) => m.type() === "error" && errs.push(m.text().slice(0, 200)));
page.on("crash", () => errs.push("PAGE CRASHED"));
await page.goto((process.env.APP_URL || "http://localhost:5173/"));
await page.evaluate(() => localStorage.clear());
await page.goto((process.env.APP_URL || "http://localhost:5173/"));
if (lang === "js") await page.getByTestId("language").selectOption("javascript");
await page.locator(".cm-content").click();
await page.keyboard.press("Meta+A"); await page.keyboard.press("Delete");
await page.keyboard.insertText(fs.readFileSync(codeFile, "utf8"));
await page.waitForTimeout(900);
if (mode === "script") await page.getByTestId("mode-script").click();
else for (const [i, a] of JSON.parse(argsJson).entries()) await page.getByTestId(`arg-${i}`).fill(a);
const t0 = Date.now();
await page.getByTestId("run").click();
let state = "?";
try { await page.locator(".app[data-run-status=done]").waitFor({ timeout: 45000 }); state = "done"; } catch { state = "TIMEOUT (still running)"; }
console.log("state:", state, "after", Date.now() - t0, "ms");
const responsive = await Promise.race([page.evaluate(() => 1 + 1), new Promise((r) => setTimeout(() => r("UI FROZEN"), 5000))]);
console.log("page responsive:", responsive);
console.log("body text length:", await page.evaluate(() => document.body.innerText.length), "| root children:", await page.evaluate(() => document.getElementById("root")?.children.length));
console.log("counter:", (await page.getByTestId("step-counter").textContent().catch(() => "n/a"))?.slice(0, 40));
console.log("errors:", errs.length, [...new Set(errs)].slice(0, 4));
await page.screenshot({ path: `${process.env.OUT}/probe-${lang}-${mode}.png` });
await browser.close();
