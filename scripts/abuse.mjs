// Dev utility: run a program, then poke every part of the UI and report crashes (blank page, page errors).
import { chromium } from "@playwright/test";
import fs from "node:fs";
const [lang, mode, codeFile, argsJson = "[]"] = process.argv.slice(2);
if (!codeFile) throw new Error("usage: abuse.mjs <py|js> <function|script> <code-file> [args-json]");
const browser = await chromium.launch({ channel: "chrome" });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errs = [];
page.on("pageerror", (e) => errs.push("pageerror: " + e.message.slice(0, 300)));
page.on("console", (m) => m.type() === "error" && errs.push("console: " + m.text().slice(0, 300)));
page.on("crash", () => errs.push("PAGE CRASHED"));
const alive = async (label) => {
  if (await page.getByTestId("crash-card").count().catch(() => 0)) errs.push(`CRASH CARD shown after: ${label}`);
  const n = await page.evaluate(() => document.getElementById("root")?.innerText.length ?? 0).catch(() => -1);
  if (n < 50) errs.push(`BLANK/DEAD PAGE after: ${label} (text length ${n})`);
};
await page.goto((process.env.APP_URL || "http://localhost:5173/"));
await page.evaluate(() => localStorage.clear());
await page.goto((process.env.APP_URL || "http://localhost:5173/"));
if (lang === "js") await page.getByTestId("language").selectOption("javascript");
await page.locator(".cm-content").click();
await page.keyboard.press("Meta+A"); await page.keyboard.press("Delete");
await page.keyboard.insertText(fs.readFileSync(codeFile, "utf8"));
await page.waitForTimeout(900);
if (mode === "script") await page.getByTestId("mode-script").click();
else for (const [i, a] of JSON.parse(argsJson).entries()) await page.getByTestId(`arg-${i}`).fill(a);
await page.getByTestId("run").click();
await page.locator(".app[data-run-status=done]").waitFor({ timeout: 60000 });
await alive("run");
const step = async (label, fn) => { try { await fn(); } catch (e) { errs.push(`ACTION FAILED ${label}: ${String(e).split("\n")[0].slice(0, 120)}`); } await page.waitForTimeout(150); await alive(label); };
await step("focus canvas", () => page.locator(".col-center").click({ position: { x: 5, y: 5 } }));
for (const k of ["ArrowRight", "ArrowRight", "ArrowLeft", "ArrowDown", "ArrowUp", "End", "Home", "End"]) await step("key " + k, () => page.keyboard.press(k));
await step("scrub mid", () => page.getByTestId("scrubber").fill("5000"));
await step("scrub end", () => page.getByTestId("scrubber").fill("9999"));
for (const t of ["side-watch", "side-history", "side-predict", "side-vars"]) await step(t, () => page.getByTestId(t).click());
await step("watch add", async () => { await page.getByTestId("side-watch").click(); await page.locator(".watch-form input").fill("len(x)"); await page.keyboard.press("Enter"); });
await step("variable history", async () => { await page.getByTestId("side-vars").click(); await page.locator(".var-name-btn").first().click(); });
await step("predict on", async () => { await page.getByTestId("side-predict").click(); await page.getByTestId("pred-enable").click(); });
await step("predict off", async () => { await page.locator(".pred-head .mini-btn").click(); });
for (const t of ["dock-output", "dock-compare", "dock-input"]) await step(t, () => page.getByTestId(t).click());
await step("play 2s", async () => { await page.keyboard.press("Home"); await page.getByTestId("play").click(); await page.waitForTimeout(2000); await page.getByTestId("play").click(); });
await step("expand var", async () => { await page.getByTestId("side-vars").click(); await page.locator(".disclosure, .var-row .var-line").first().click(); });
await step("breakpoint line", () => page.locator(".cm-lineNumbers .cm-gutterElement").nth(2).click());
await step("next breakpoint", () => page.getByTestId("next-bp").click());
await step("edit code", async () => { await page.getByTestId("edit-code").click(); });
await step("rerun", async () => { await page.getByTestId("run").click(); await page.locator(".app[data-run-status=done]").waitFor({ timeout: 60000 }); });
await step("rerun again quickly", async () => { await page.getByTestId("run").click(); await page.waitForTimeout(300); await page.getByTestId("stop").click().catch(() => {}); await page.waitForTimeout(1500); });
console.log("errors:", errs.length); for (const e of [...new Set(errs)].slice(0, 12)) console.log(" -", e);
await page.screenshot({ path: `${process.env.OUT}/abuse-${lang}-${mode}.png` });
await browser.close();
